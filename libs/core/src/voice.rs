// hako-stt worker protocol: frames on the worker's stdin / stdout.
// Frame = u32 LE length (of kind byte + body), kind byte, body.
// Kind 0: JSON (`WorkerIn` / `WorkerOut`); kind 1: PCM, f32 LE mono 16 kHz.

pub mod worker {
    use super::ModelCaps;
    use serde::{Deserialize, Serialize};
    use std::io::{self, Read, Write};

    /// Largest frame either side accepts.
    pub const MAX_FRAME: usize = 4 * 1024 * 1024;
    const KIND_JSON: u8 = 0;
    const KIND_PCM: u8 = 1;

    #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
    #[serde(tag = "type", rename_all = "snake_case")]
    pub enum WorkerIn {
        /// Load a model (replacing any loaded one). `vad`: Silero VAD file.
        Load {
            path: String,
            #[serde(default)]
            vad: Option<String>,
            /// `None` = automatic; else a name from `Ready::devices`.
            #[serde(default)]
            device: Option<String>,
            #[serde(default)]
            cpu_only: bool,
        },
        /// Start an utterance session; PCM frames follow until `End`.
        Begin {
            session: u64,
            /// Stream (model must support it); else batch.
            streaming: bool,
            /// Batch only: output each utterance at a pause this long (ms).
            #[serde(default)]
            pause_ms: Option<u32>,
            /// Batch only: drop silence with VAD before decoding.
            #[serde(default)]
            vad: bool,
            #[serde(default)]
            language: Option<String>,
            #[serde(default)]
            translate: bool,
            #[serde(default)]
            vocabulary: Vec<String>,
            #[serde(default)]
            punctuation: Option<bool>,
        },
        End {
            session: u64,
        },
        Cancel {
            session: u64,
        },
        Unload,
        /// Listen for wake words until `End`: PCM frames follow without end.
        /// Needs no loaded model.
        Wake {
            session: u64,
            /// The extracted keyword-spotting model (`voice::kws_dir()`).
            model_dir: String,
            /// Phrases (English letters), e.g. `["jarvis"]`.
            keywords: Vec<String>,
            /// From `voice::wake_params`.
            threshold: f32,
            boost: f32,
        },
    }

    #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
    #[serde(tag = "type", rename_all = "snake_case")]
    pub enum WorkerOut {
        /// First frame after start.
        Ready {
            version: String,
            devices: Vec<String>,
        },
        Loaded {
            caps: ModelCaps,
        },
        /// Streaming: the live hypothesis (committed only grows).
        Partial {
            session: u64,
            committed: String,
            tentative: String,
        },
        /// Batch with pauses: one finished utterance, output it now.
        Segment {
            session: u64,
            text: String,
        },
        /// The session's final text (all of it, after `End`).
        Final {
            session: u64,
            text: String,
            #[serde(default)]
            language: Option<String>,
        },
        /// VAD: speech started / stopped (Jarvis, UI).
        Speech {
            session: u64,
            active: bool,
        },
        /// A wake word was heard (its phrase, as configured).
        Wake {
            session: u64,
            keyword: String,
        },
        Error {
            #[serde(default)]
            session: Option<u64>,
            message: String,
        },
    }

    #[derive(Debug, Clone, PartialEq)]
    pub enum Frame<T> {
        Msg(T),
        Pcm(Vec<f32>),
    }

    pub fn write_msg<T: Serialize>(w: &mut impl Write, msg: &T) -> io::Result<()> {
        let body = serde_json::to_vec(msg).map_err(io::Error::other)?;
        write_raw(w, KIND_JSON, &body)
    }

    pub fn write_pcm(w: &mut impl Write, pcm: &[f32]) -> io::Result<()> {
        let body: Vec<u8> = pcm.iter().flat_map(|s| s.to_le_bytes()).collect();
        write_raw(w, KIND_PCM, &body)
    }

    fn write_raw(w: &mut impl Write, kind: u8, body: &[u8]) -> io::Result<()> {
        let len = body.len() + 1;
        if len > MAX_FRAME {
            return Err(io::Error::other("frame too large"));
        }
        w.write_all(&(len as u32).to_le_bytes())?;
        w.write_all(&[kind])?;
        w.write_all(body)?;
        w.flush()
    }

    /// `Ok(None)` at a clean end of stream.
    pub fn read_frame<T: for<'de> Deserialize<'de>>(
        r: &mut impl Read,
    ) -> io::Result<Option<Frame<T>>> {
        let mut len = [0u8; 4];
        match r.read_exact(&mut len) {
            Err(e) if e.kind() == io::ErrorKind::UnexpectedEof => return Ok(None),
            other => other?,
        }
        let len = u32::from_le_bytes(len) as usize;
        if len == 0 || len > MAX_FRAME {
            return Err(io::Error::other(format!("bad frame length {len}")));
        }
        let mut buf = vec![0u8; len];
        r.read_exact(&mut buf)?;
        match buf[0] {
            KIND_JSON => serde_json::from_slice(&buf[1..])
                .map(|m| Some(Frame::Msg(m)))
                .map_err(io::Error::other),
            KIND_PCM if (len - 1).is_multiple_of(4) => Ok(Some(Frame::Pcm(
                buf[1..]
                    .as_chunks::<4>()
                    .0
                    .iter()
                    .map(|c| f32::from_le_bytes(*c))
                    .collect(),
            ))),
            k => Err(io::Error::other(format!("bad frame kind {k}"))),
        }
    }
}

