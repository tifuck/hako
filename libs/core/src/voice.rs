/// The catalog this build ships with.
pub static CATALOG: LazyLock<Catalog> = LazyLock::new(|| {
    serde_json::from_str(include_str!("voice_catalog.json")).expect("voice_catalog.json parses")
});

/// `~/.local/share/hako`: models, history (data, not config).
pub fn data_dir() -> Result<PathBuf> {
    Ok(dirs::data_dir().context("no data dir")?.join("hako"))
}

pub fn models_dir() -> Result<PathBuf> {
    Ok(data_dir()?.join("models"))
}

/// The extracted wake-word model (`models/kws/<archive dir>`).
pub fn kws_dir() -> Result<PathBuf> {
    Ok(models_dir()?.join("kws").join(&CATALOG.kws.dir))
}

/// Wake-word sensitivity (0..=1, higher wakes more easily) as the spotter's
/// trigger threshold and keyword boost.
pub fn wake_params(sensitivity: f32) -> (f32, f32) {
    let s = sensitivity.clamp(0.0, 1.0);
    (0.6 - 0.45 * s, 1.0 + 2.0 * s)
}

/// Where a catalog file lives once downloaded (`<file>` in the models dir;
/// the file name carries model and quant).
pub fn model_path(file: &CatalogFile) -> Result<PathBuf> {
    Ok(models_dir()?.join(&file.file))
}

