fn in_range(name: &str, v: u32, (lo, hi): (u32, u32)) -> Result<(), String> {
    if (lo..=hi).contains(&v) {
        Ok(())
    } else {
        Err(format!("{name} must be {lo}..={hi}"))
    }
}

fn check_words(name: &str, words: &[String], max: usize) -> Result<(), String> {
    if words.len() > max {
        return Err(format!("at most {max} {name}"));
    }
    if words
        .iter()
        .any(|w| w.trim().is_empty() || w.len() > MAX_WORD_LEN || w.contains(['\n', '\0']))
    {
        return Err(format!(
            "{name}: 1 to {MAX_WORD_LEN} characters, one line each"
        ));
    }
    Ok(())
}

fn check_model(choice: &ModelChoice) -> Result<(), String> {
    match choice {
        ModelChoice::Catalog { id, quant } => {
            let m = CATALOG
                .model(id)
                .ok_or_else(|| format!("unknown model {id:?}"))?;
            m.file(quant)
                .ok_or_else(|| format!("{id} has no {quant} file"))?;
        }
        ModelChoice::Custom { file } => {
            if !valid_custom_file(file) {
                return Err(format!("invalid model file name {file:?}"));
            }
        }
    }
    Ok(())
}

/// A plain `*.gguf` file name (no path).
pub fn valid_custom_file(file: &str) -> bool {
    file.ends_with(".gguf")
        && file.len() <= 255
        && !file.starts_with('.')
        && !file.contains(['/', '\\', '\0'])
}

fn check_lang(lang: &Option<String>) -> Result<(), String> {
    match lang {
        Some(l) if l.is_empty() || l.len() > 8 || !l.bytes().all(|b| b.is_ascii_alphabetic()) => {
            Err(format!("invalid language code {l:?}"))
        }
        _ => Ok(()),
    }
}

fn check_program(name: &str, p: &Option<String>, absolute: bool) -> Result<(), String> {
    if let Some(p) = p {
        if p.is_empty() || p.contains('\0') || (absolute && !p.starts_with('/')) {
            return Err(format!(
                "{name}: {}",
                if absolute {
                    "an absolute path"
                } else {
                    "a program name"
                }
            ));
        }
        if !absolute && p.contains(['/', ' ']) {
            return Err(format!("{name}: a program name, no path or arguments"));
        }
    }
    Ok(())
}

impl VoiceFile {
    pub fn validate(&self) -> Result<(), String> {
        if let Some(m) = &self.model {
            check_model(m)?;
        }
        if let Some(m) = &self.alt.model {
            check_model(m)?;
        }
        check_lang(&self.language)?;
        check_lang(&self.alt.language)?;
        if self
            .mic
            .as_ref()
            .is_some_and(|m| m.is_empty() || m.len() > 255)
        {
            return Err("invalid microphone".into());
        }
        let o = &self.output;
        in_range("key delay", o.key_delay_ms, KEY_DELAY_MS_RANGE)?;
        in_range("clipboard restore", o.restore_ms, (0, 5000))?;
        check_program("external tool", &o.external_tool, false)?;
        check_program("command", &o.command, true)?;
        if o.method == OutputMethod::External && o.external_tool.is_none() {
            return Err("pick an external tool".into());
        }
        if o.method == OutputMethod::Command && o.command.is_none() {
            return Err("pick a command".into());
        }
        if let Some(l) = &o.layout {
            if l.is_empty()
                || l.len() > 32
                || !l
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b"_-()".contains(&b))
            {
                return Err("invalid keyboard layout".into());
            }
        }
        in_range("pause length", self.streaming.pause_ms, PAUSE_MS_RANGE)?;
        if !(0.0..=1.0).contains(&self.sounds.volume) {
            return Err("volume must be 0..=1".into());
        }
        check_words("custom words", &self.text.custom_words, MAX_CUSTOM_WORDS)?;
        check_words("filler words", &self.text.fillers, MAX_CUSTOM_WORDS)?;
        if self.text.replacements.len() > MAX_REPLACEMENTS
            || self.text.replacements.iter().any(|r| {
                r.from.trim().is_empty() || r.from.len() > MAX_WORD_LEN || r.to.len() > 256
            })
        {
            return Err(format!(
                "replacements: at most {MAX_REPLACEMENTS}, each \"from\" 1 to {MAX_WORD_LEN} characters"
            ));
        }
        in_range("history", self.history.keep, (0, MAX_HISTORY))?;
        in_range("maximum length", self.advanced.max_seconds, MAX_RECORDING_S)?;
        if let Some(s) = self.advanced.unload_after_s {
            in_range("unload after", s, (0, 86_400))?;
        }
        let w = self.jarvis.wake_word.trim();
        if w.is_empty() || w.len() > 32 || w.split_whitespace().count() > 3 {
            return Err("wake word: 1 to 3 words".into());
        }
        if !(0.0..=1.0).contains(&self.jarvis.sensitivity) {
            return Err("sensitivity must be 0..=1".into());
        }
        if !w
            .chars()
            .all(|c| c.is_ascii_alphabetic() || c == ' ' || c == '\'')
        {
            return Err("wake word: English letters only".into());
        }
        if self.jarvis.commands.len() > MAX_USER_COMMANDS {
            return Err(format!("at most {MAX_USER_COMMANDS} commands"));
        }
        for c in &self.jarvis.commands {
            if c.say.is_empty()
                || c.say.len() > 8
                || c.say
                    .iter()
                    .any(|s| s.trim().is_empty() || s.len() > 64 || s.matches('{').count() > 1)
            {
                return Err("command: 1 to 8 phrases, each 1 to 64 characters".into());
            }
            match &c.action {
                UserAction::Run { program, args } => {
                    if !program.starts_with('/') || program.contains('\0') || args.len() > 32 {
                        return Err("command: the program is an absolute path".into());
                    }
                }
                UserAction::Keys { keys } if keys.is_empty() || keys.len() > 4 => {
                    return Err("command: 1 to 4 keys".into());
                }
                UserAction::Type { text } if text.is_empty() || text.len() > 4096 => {
                    return Err("command: text to type, at most 4096 characters".into());
                }
                UserAction::Open { target } if target.is_empty() || target.contains('\0') => {
                    return Err("command: a URL or path to open".into());
                }
                UserAction::Profile { name } if name.trim().is_empty() || name.len() > 64 => {
                    return Err(format!("command: invalid profile name {name:?}"));
                }
                _ => {}
            }
        }
        if let Some(u) = &self.jarvis.search_url {
            if !(u.starts_with("https://") || u.starts_with("http://")) || !u.contains("{q}") {
                return Err("search URL: http(s) with {q}".into());
            }
        }
        Ok(())
    }
}

/// Serialises every read-modify-write of `voice.toml` in this process.
static VOICE_LOCK: Mutex<()> = Mutex::new(());

pub fn voice_path(paths: &ConfigPaths) -> PathBuf {
    paths.root.join("voice.toml")
}

/// Defaults when missing; an unparsable file is an error, never replaced.
pub fn load_voice(paths: &ConfigPaths) -> Result<VoiceFile> {
    let path = voice_path(paths);
    let text = match std::fs::read_to_string(&path) {
        Ok(t) => t,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(VoiceFile::default()),
        Err(e) => return Err(e).with_context(|| format!("read {}", path.display())),
    };
    let file: VoiceFile =
        toml::from_str(&text).with_context(|| format!("parse {}", path.display()))?;
    if file.version > VOICE_VERSION {
        bail!(
            "{} is version {} (this hako reads {VOICE_VERSION})",
            path.display(),
            file.version
        );
    }
    Ok(file)
}

/// Load, edit, validate and save `voice.toml` as one step.
pub fn update_voice<T>(
    paths: &ConfigPaths,
    edit: impl FnOnce(&mut VoiceFile) -> Result<T, String>,
) -> Result<(VoiceFile, T)> {
    let _guard = VOICE_LOCK.lock().unwrap_or_else(|p| p.into_inner());
    let mut file = load_voice(paths)?;
    let out = edit(&mut file).map_err(anyhow::Error::msg)?;
    file.validate().map_err(anyhow::Error::msg)?;
    std::fs::create_dir_all(&paths.root)?;
    write_atomic(&voice_path(paths), &toml::to_string_pretty(&file)?)?;
    Ok((file, out))
}

