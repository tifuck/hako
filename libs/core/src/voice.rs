#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum OutputMethod {
    /// Virtual keyboard, as text arrives (streams into the focused field).
    #[default]
    Type,
    /// Clipboard + paste key per utterance, then the clipboard is restored.
    Paste,
    /// `wtype` / `ydotool` / `dotool` / `xdotool` (`external_tool`).
    External,
    /// Copy only.
    Clipboard,
    /// Run `command` with the text on stdin; its stdout is typed.
    Command,
}

impl OutputMethod {
    pub const ALL: [Self; 5] = [
        Self::Type,
        Self::Paste,
        Self::External,
        Self::Clipboard,
        Self::Command,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Self::Type => "Type (live)",
            Self::Paste => "Paste",
            Self::External => "External tool",
            Self::Clipboard => "Clipboard only",
            Self::Command => "Command",
        }
    }

    /// Text can be output piece by piece while speaking.
    pub fn is_live(self) -> bool {
        self == Self::Type
    }
}

