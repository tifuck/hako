#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CatalogFile {
    pub quant: String,
    /// Pinned to the repo commit: always this exact file.
    pub url: String,
    pub file: String,
    pub size: u64,
    pub sha256: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CatalogModel {
    pub id: String,
    pub name: String,
    pub repo: String,
    #[serde(default)]
    pub base_model: String,
    #[serde(default)]
    pub license: String,
    /// ISO codes; one entry for single-language models.
    #[serde(default)]
    pub languages: Vec<String>,
    /// Text appears while speaking (otherwise at pauses / at the end).
    pub streaming: bool,
    #[serde(default)]
    pub translate: bool,
    #[serde(default)]
    pub lang_detect: bool,
    /// Approximate parameter count (from the full-precision file size).
    #[serde(default)]
    pub params: Option<u64>,
    /// LibriSpeech test-clean WER (%) per quant (`Q8_0`, ...), when measured.
    #[serde(default)]
    pub wer_en: std::collections::BTreeMap<String, f64>,
    /// Real-time factor on a laptop CPU (Ryzen 4750U); higher is faster.
    #[serde(default)]
    pub rtf_cpu: Option<f64>,
    pub files: Vec<CatalogFile>,
}

impl CatalogModel {
    pub fn file(&self, quant: &str) -> Option<&CatalogFile> {
        self.files.iter().find(|f| f.quant == quant)
    }

    /// `Q8_0` when published, else the smallest file.
    pub fn default_quant(&self) -> &str {
        self.file("Q8_0")
            .or_else(|| self.files.first())
            .map_or("", |f| f.quant.as_str())
    }

    /// The model is not for commercial use (`-nc` licences).
    pub fn non_commercial(&self) -> bool {
        self.license.contains("-nc")
    }
}

