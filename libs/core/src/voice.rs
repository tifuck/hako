    #[test]
    fn validation() {
        let mut f = VoiceFile {
            model: Some(ModelChoice::Catalog {
                id: "nope".into(),
                quant: "Q8_0".into(),
            }),
            ..Default::default()
        };
        assert!(f.validate().is_err());
        f.model = Some(ModelChoice::Custom {
            file: "../x.gguf".into(),
        });
        assert!(f.validate().is_err());
        f.model = Some(ModelChoice::Custom {
            file: "mine.gguf".into(),
        });
        f.validate().unwrap();
        f.output.method = OutputMethod::Command;
        assert!(f.validate().is_err());
        f.output.command = Some("relative".into());
        assert!(f.validate().is_err());
        f.output.command = Some("/usr/bin/tr".into());
        f.validate().unwrap();
        f.jarvis.wake_word = "a b c d".into();
        assert!(f.validate().is_err());
    }

    #[test]
    fn frames_round_trip() {
        let mut buf = Vec::new();
        write_msg(&mut buf, &WorkerIn::End { session: 7 }).unwrap();
        write_pcm(&mut buf, &[0.5, -1.0]).unwrap();
        let mut r = &buf[..];
        assert_eq!(
            read_frame::<WorkerIn>(&mut r).unwrap(),
            Some(Frame::Msg(WorkerIn::End { session: 7 }))
        );
        assert_eq!(
            read_frame::<WorkerIn>(&mut r).unwrap(),
            Some(Frame::Pcm(vec![0.5, -1.0]))
        );
        assert_eq!(read_frame::<WorkerIn>(&mut r).unwrap(), None);
    }
